#!/bin/bash
# initramfs for the MMU Linux : busybox built without CONFIG_NOMMU (ash, fork)
#   BUSYBOX  busybox source / build directory (default ~/linux/busybox-1.36.1-mmu,
#            built with the musl wrapper : make CC=~/linux/musl-rv32/bin/riscv32-musl-gcc)
#   ROOTFS   extra files : init, bin/mtest (default ~/linux/initramfs-mmu)
#   GENCPIO  gen_init_cpio of a kernel tree (default ~/linux/linux/usr/gen_init_cpio)
#   OUT      output (default ~/linux/initramfs-mmu.cpio)
#   no root needed : the device nodes are made by gen_init_cpio
set -e
BUSYBOX=${BUSYBOX:-$HOME/linux/busybox-1.36.1-mmu}
ROOTFS=${ROOTFS:-$HOME/linux/initramfs-mmu}
GENCPIO=${GENCPIO:-$HOME/linux/linux/usr/gen_init_cpio}
OUT=${OUT:-$HOME/linux/initramfs-mmu.cpio}
LIST=${OUT%.cpio}.list
make -s -C $BUSYBOX busybox.links
{
    echo "# generated by linux_mmu/mkinitramfs.sh"
    echo "dir /dev 755 0 0"
    echo "nod /dev/console 600 0 0 c 5 1"
    echo "nod /dev/null 666 0 0 c 1 3"
    echo "nod /dev/ttyMY0 600 0 0 c 4 64"
    for d in /proc /sys /tmp /etc /bin /sbin /usr /usr/bin /usr/sbin; do
        echo "dir $d 755 0 0"
    done
    echo "file /bin/busybox $BUSYBOX/busybox 755 0 0"
    [ -f $ROOTFS/bin/mtest ] && echo "file /bin/mtest $ROOTFS/bin/mtest 755 0 0"
    echo "file /init $ROOTFS/init 755 0 0"
    while read p; do
        case $p in
            /bin/*) t=busybox ;;
            /sbin/*) t=../bin/busybox ;;
            /usr/bin/*|/usr/sbin/*) t=../../bin/busybox ;;
            *) continue ;;
        esac
        echo "slink $p $t 777 0 0"
    done < $BUSYBOX/busybox.links
} > $LIST
$GENCPIO $LIST > $OUT
ls -la $OUT
